"""Language-model clients behind one small interface."""

from typing import Protocol

import httpx

from app.config import Settings


class LLMError(Exception):
    pass


class LLMClient(Protocol):
    async def generate(self, system_prompt: str, user_content: str) -> str: ...


class FakeLLMClient:
    """Deterministic client for local development and tests: no network, no API key."""

    async def generate(self, system_prompt: str, user_content: str) -> str:
        first_line = user_content.splitlines()[0] if user_content else "Unknown customer"
        return (
            "## Summary\n"
            f"{first_line}. Report generated by the fake LLM provider.\n\n"
            "## Opportunities\n"
            "- Review the customer's recent requests\n\n"
            "## Suggested opener\n"
            "Hello, I saw your recent messages, let's go through them together."
        )


class OpenAICompatibleClient:
    """Calls any OpenAI-compatible /chat/completions endpoint (OpenAI, Mistral, Ollama, ...)."""

    def __init__(self, settings: Settings, transport: httpx.AsyncBaseTransport | None = None):
        if not settings.llm_api_key:
            raise LLMError("LLM_API_KEY is required when LLM_PROVIDER=openai")
        self._model = settings.llm_model
        self._client = httpx.AsyncClient(
            base_url=settings.llm_base_url,
            headers={"Authorization": f"Bearer {settings.llm_api_key}"},
            timeout=settings.llm_timeout_seconds,
            transport=transport,
        )

    async def generate(self, system_prompt: str, user_content: str) -> str:
        payload = {
            "model": self._model,
            "messages": [
                {"role": "system", "content": system_prompt},
                {"role": "user", "content": user_content},
            ],
            "temperature": 0.2,
        }
        try:
            response = await self._client.post("/chat/completions", json=payload)
            response.raise_for_status()
            content = response.json()["choices"][0]["message"]["content"]
        except httpx.HTTPStatusError as exc:
            raise LLMError(f"LLM returned HTTP {exc.response.status_code}") from exc
        except httpx.HTTPError as exc:
            raise LLMError(f"LLM request failed: {exc.__class__.__name__}") from exc
        except (KeyError, IndexError, ValueError) as exc:
            raise LLMError("Unexpected LLM response format") from exc
        if not content or not content.strip():
            raise LLMError("LLM returned an empty report")
        return content.strip()

    async def aclose(self) -> None:
        await self._client.aclose()


def build_llm_client(settings: Settings) -> LLMClient:
    if settings.llm_provider == "openai":
        return OpenAICompatibleClient(settings)
    return FakeLLMClient()
